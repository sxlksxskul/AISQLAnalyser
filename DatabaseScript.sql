-- 1. CLUB: The primary parent table
CREATE TABLE CLUB (
    id INT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    city VARCHAR(100),
    address VARCHAR(255),
    email VARCHAR(100),
    contact VARCHAR(50),
    website VARCHAR(255)
);

-- 2. JUDGE: Independent official records
CREATE TABLE JUDGE (
    BIB INT PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    date_of_birth DATE
);

-- 3. TRAINER: Linked to a specific club
CREATE TABLE TRAINER (
    BIB INT PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    date_of_birth DATE,
    phone_number VARCHAR(50),
    club_id INT,
    FOREIGN KEY (club_id) REFERENCES CLUB(id)
);

-- 4. ATHLETE: Linked to a specific club
CREATE TABLE ATHLETE (
    BIB INT PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    date_of_birth DATE,
    club_id INT,
    FOREIGN KEY (club_id) REFERENCES CLUB(id)
);

-- 5. COMPETITION: Managed by a specific club
CREATE TABLE COMPETITION (
    id INT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    date DATE,
    location VARCHAR(255),
    category VARCHAR(100),
    competition_format VARCHAR(100),
    competition_capacity INT,
    competition_director VARCHAR(100),
    entry_fee DECIMAL(10, 2),
    club_id INT,
    FOREIGN KEY (club_id) REFERENCES CLUB(id)
);

-- 6. TRAINER_LICENSE: Details for trainers
CREATE TABLE TRAINER_LICENSE (
    id INT PRIMARY KEY,
    type VARCHAR(100),
    description TEXT,
    trainer_BIB INT,
    FOREIGN KEY (trainer_BIB) REFERENCES TRAINER(BIB)
);

-- 7. MEDICAL_CLEARANCE: Health records for athletes
CREATE TABLE MEDICAL_CLEARANCE (
    id INT PRIMARY KEY,
    exam_date DATE,
    expiration_date DATE,
    comment TEXT,
    athlete_BIB INT,
    FOREIGN KEY (athlete_BIB) REFERENCES ATHLETE(BIB)
);

-- 8. ATHLETE_COMPETITION: Results junction table
CREATE TABLE ATHLETE_COMPETITION (
    athlete_BIB INT,
    competition_id INT,
    category VARCHAR(100),
    qualification_result VARCHAR(255),
    rank_achieved VARCHAR(50),
    PRIMARY KEY (athlete_BIB, competition_id),
    FOREIGN KEY (athlete_BIB) REFERENCES ATHLETE(BIB),
    FOREIGN KEY (competition_id) REFERENCES COMPETITION(id)
);

-- 9. JUDGE_COMPETITION: Officiating junction table
CREATE TABLE JUDGE_COMPETITION (
    judge_BIB INT,
    competition_id INT,
    report TEXT,
    PRIMARY KEY (judge_BIB, competition_id),
    FOREIGN KEY (judge_BIB) REFERENCES JUDGE(BIB),
    FOREIGN KEY (competition_id) REFERENCES COMPETITION(id)
);

